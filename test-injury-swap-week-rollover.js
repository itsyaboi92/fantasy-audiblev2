'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const context=require('./injury-substitutions');
const src=fs.readFileSync(__dirname+'/server.js','utf8');
const state={week:10,players:[{id:'old',scoringMode:'later',scoreAtSwap:0,credited:11},{id:'new',scoringMode:'handcuff',scoreAtSwap:3,credited:2}],injurySwapHistory:[{week:9,replacementId:'old',removedId:'removed'},{week:10,replacementId:'new',removedId:'another'}],injuries:[{id:'i9',player:'old',active:true,week:9},{id:'i10',player:'new',active:true,week:10}]};
assert.equal(context.activeSwapMode(state,state.players[0]),false);
assert.equal(context.activeSwapMode(state,state.players[1]),true);
context.expireOldInjuryState(state);
assert.equal(state.players[0].scoringMode,undefined);
assert.equal(state.players[0].scoreAtSwap,undefined);
assert.equal(state.players[1].scoringMode,'handcuff');
assert.equal(state.players[1].scoreAtSwap,3);
assert.equal(state.injuries[0].active,false);
assert.equal(state.injuries[1].active,true);
assert.equal(context.injurySwapRetired(state,{id:'removed'}),false);
assert.equal(context.injurySwapRetired(state,{id:'another'}),true);
assert.equal(context.pendingInjury(state,state.players[0]),false);
assert.equal(context.pendingInjury(state,state.players[1]),true);
assert.equal(state.injurySwapHistory.length,2);
assert(src.includes('expireOldInjuryState(s);'));
console.log('PASS injury substitution week isolation and rollover');
